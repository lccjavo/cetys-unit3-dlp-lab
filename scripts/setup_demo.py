"""Exercise B - Generate a vulnerable configuration containing a FICTIONAL credential.

The file is created at practice/app/config.py, a directory ignored by Git.
Every run generates a new random token in the synthetic format matched by
the "cetys-lab-token" rule in .gitleaks.toml.

Usage:
  python scripts/setup_demo.py           # create the vulnerable configuration
  python scripts/setup_demo.py --fix     # write the fixed version (fallback for step B2)
"""

from __future__ import annotations

import argparse
import secrets
import string
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from lab_utils import PRACTICE_DIR, configure_console, display_path  # noqa: E402

TOKEN_PREFIX = "cetyslab_sk_"
TOKEN_LENGTH = 32
APP_DIR = PRACTICE_DIR / "app"
CONFIG_NAME = "config.py"

VULNERABLE_TEMPLATE = '''\
# "Payments Portal" configuration (FICTIONAL application for the CETYS lab)
# Generated by scripts/setup_demo.py. The credential is NOT real.

API_URL = "https://payments.example.local/api/v1"
TIMEOUT_SECONDS = 30

# BAD PRACTICE: the credential is hardcoded in the source code.
PAYMENTS_API_TOKEN = "{token}"
'''

FIXED_TEMPLATE = '''\
# "Payments Portal" configuration (FICTIONAL application for the CETYS lab)
import os

API_URL = "https://payments.example.local/api/v1"
TIMEOUT_SECONDS = 30

# GOOD PRACTICE: the credential is read from the environment (or a secrets manager)
# and is never stored in the repository.
PAYMENTS_API_TOKEN = os.environ.get("PAYMENTS_API_TOKEN", "")
'''


def generate_token() -> str:
    """Generate a random synthetic token; it is never written to tracked files."""
    alphabet = string.ascii_letters + string.digits
    return TOKEN_PREFIX + "".join(secrets.choice(alphabet) for _ in range(TOKEN_LENGTH))


def create_vulnerable_config(directory: Path = APP_DIR) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / CONFIG_NAME
    path.write_text(VULNERABLE_TEMPLATE.format(token=generate_token()), encoding="utf-8")
    return path


def create_fixed_config(directory: Path = APP_DIR) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / CONFIG_NAME
    path.write_text(FIXED_TEMPLATE, encoding="utf-8")
    return path


def main(argv: list[str] | None = None) -> int:
    configure_console()
    parser = argparse.ArgumentParser(description="Prepare the practice configuration for Gitleaks.")
    parser.add_argument("--fix", action="store_true", help="write the fixed version of the file")
    args = parser.parse_args(argv)

    if args.fix:
        path = create_fixed_config()
        print(f"[OK] Fixed configuration written to: {display_path(path)}")
        print('The credential was replaced with os.environ.get("PAYMENTS_API_TOKEN", "").')
        return 0

    path = create_vulnerable_config()
    print(f"[OK] Vulnerable configuration created at: {display_path(path)}")
    print("It contains a FICTIONAL credential in the lab format (cetyslab_sk_...).")
    print("The practice/ directory is listed in .gitignore: this file must never be committed.")
    print()
    print("Next step:")
    print("  gitleaks dir practice/app --config .gitleaks.toml --redact --verbose")
    return 0


if __name__ == "__main__":
    sys.exit(main())
